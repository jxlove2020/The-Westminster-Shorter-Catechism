function normalizeRef(ref) {
  return String(ref || '')
    .replace(/\s+/g, '')
    .replace(/-/g, '~')
    .replace(/[()[\]]/g, '');
}

function expandRefs(refsText) {
  if (!refsText) return [];

  const parts = String(refsText)
    .split(',')
    .map(part => part.trim())
    .filter(Boolean);

  const expanded = [];
  let currentBook = '';
  let currentChapter = '';

  for (const part of parts) {
    if (part.includes('참조')) {
      expanded.push(part);
      continue;
    }

    let match = part.match(/^([^\d\s,]+)\s*(\d+):(.+)$/);
    if (match) {
      currentBook = match[1];
      currentChapter = match[2];
      expanded.push(`${currentBook} ${currentChapter}:${match[3].trim()}`);
      continue;
    }

    match = part.match(/^([^\d\s,]+)\s*(\d+편)$/);
    if (match) {
      currentBook = match[1];
      currentChapter = '';
      expanded.push(`${currentBook} ${match[2]}`);
      continue;
    }

    match = part.match(/^(\d+):(.+)$/);
    if (match && currentBook) {
      currentChapter = match[1];
      expanded.push(`${currentBook} ${currentChapter}:${match[2].trim()}`);
      continue;
    }

    match = part.match(/^(\d+편)$/);
    if (match && currentBook) {
      currentChapter = '';
      expanded.push(`${currentBook} ${match[1]}`);
      continue;
    }

    match = part.match(/^(\d+(?:[~\-]\d+)?)$/);
    if (match && currentBook && currentChapter) {
      expanded.push(`${currentBook} ${currentChapter}:${match[1]}`);
      continue;
    }

    expanded.push(part);
  }

  return expanded;
}

const verseTextLibrary = new Map();

for (const item of catechism) {
  for (const verse of Array.isArray(item.verses) ? item.verses : []) {
    if (!verse || !verse.ref || !verse.text) continue;
    const key = normalizeRef(verse.ref);
    if (!verseTextLibrary.has(key)) {
      verseTextLibrary.set(key, verse.text);
    }
  }
}

for (const item of catechism) {
  if (!item.refs) continue;

  const targetRefs = expandRefs(item.refs);
  const existingVerses = Array.isArray(item.verses) ? item.verses : [];
  const verseMap = new Map();

  for (const verse of existingVerses) {
    if (!verse || !verse.ref) continue;
    verseMap.set(normalizeRef(verse.ref), verse);
  }

  targetRefs.forEach(ref => {
    const key = normalizeRef(ref);
    if (!verseMap.has(key)) {
      const sharedText = verseTextLibrary.get(key) || '';
      const newVerse = { ref, text: sharedText };
      existingVerses.push(newVerse);
      verseMap.set(key, newVerse);
    }
  });

  item.verses = existingVerses;
}
